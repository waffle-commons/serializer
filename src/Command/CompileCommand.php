<?php

declare(strict_types=1);

namespace Waffle\Commons\Serializer\Command;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use ReflectionClass;
use SplFileInfo;
use Waffle\Commons\Contracts\Attribute\Dto;
use Waffle\Commons\Contracts\Console\CommandInterface;
use Waffle\Commons\Contracts\Console\Enum\ExitCode;
use Waffle\Commons\Contracts\Console\InputInterface;
use Waffle\Commons\Contracts\Console\OutputInterface;
use Waffle\Commons\Serializer\Compiler\NormalizerCompiler;
use Waffle\Commons\Serializer\Normalizer\CompiledNormalizerLoader;
use Waffle\Commons\Utils\Exception\UnsupportedDtoShapeException;
use Waffle\Commons\Utils\Service\ClassParser;

use function array_key_exists;
use function basename;
use function class_exists;
use function count;
use function file_exists;
use function file_get_contents;
use function file_put_contents;
use function getmypid;
use function glob;
use function hrtime;
use function is_dir;
use function mkdir;
use function rename;
use function sort;
use function sprintf;
use function str_contains;
use function unlink;

/**
 * `waffle serializer:compile` — compiles the normalizer of every `#[Dto]` class
 * under a source directory, for the `WAFFLE_AOT=1` fast path (API-02).
 *
 * It finds the DTOs by scanning the PHP files (the class name comes from
 * `utils`' tokenizer-based `ClassParser`), hands them to the
 * {@see NormalizerCompiler}, and writes one file per class, each atomically, into
 * the directory {@see CompiledNormalizerLoader} reads. A file a previous run
 * generated for a DTO that no longer exists is removed; any other file in the
 * directory is left alone.
 *
 * Like `container:compile`, it runs at build time, after every change to a DTO.
 */
final readonly class CompileCommand implements CommandInterface
{
    public const string DEFAULT_SOURCE = 'src';

    /** The text every generated file carries; only such files are ever removed. */
    private const string GENERATED_MARKER = 'Generated by waffle-commons/serializer';

    public function __construct(
        private NormalizerCompiler $compiler = new NormalizerCompiler(),
        private ClassParser $parser = new ClassParser(),
    ) {}

    #[\Override]
    public function getName(): string
    {
        return 'serializer:compile';
    }

    #[\Override]
    public function getDescription(): string
    {
        return 'Compiles the normalizer of every #[Dto] class for the WAFFLE_AOT=1 fast path.';
    }

    #[\Override]
    public function getHelp(): string
    {
        return (
            "Scans the source directory for #[Dto] classes and writes their compiled\n"
            . "normalizers, one file per class, where the WAFFLE_AOT=1 loader reads them.\n"
            . "Re-run it after any change to a DTO.\n\n"
            . "  --source=<dir>          Where the DTOs live (default: src).\n"
            . "  --output=<dir>          Where to write (default: var/cache/serializer).\n"
            . '  --namespace=<namespace> The namespace of the generated classes (default: Waffle\\Generated\\Serializer).'
        );
    }

    #[\Override]
    public function getSynopsis(): string
    {
        return 'serializer:compile [--source=<dir>] [--output=<dir>] [--namespace=<namespace>]';
    }

    #[\Override]
    public function execute(InputInterface $input, OutputInterface $output): int
    {
        $source = $input->getOption('source') ?? self::DEFAULT_SOURCE;
        $target = $input->getOption('output') ?? CompiledNormalizerLoader::DEFAULT_DIRECTORY;
        $namespace = $input->getOption('namespace') ?? NormalizerCompiler::DEFAULT_NAMESPACE;

        if (!is_dir($source)) {
            $output->writeError(sprintf('The source directory "%s" does not exist.', $source));

            return ExitCode::NO_INPUT->value;
        }

        $classes = $this->dtoClasses($source);

        try {
            $files = $this->compiler->compile($classes, $namespace);
        } catch (UnsupportedDtoShapeException $exception) {
            $output->writeError(sprintf('Serializer compilation failed: %s', $exception->getMessage()));

            return ExitCode::DATA_ERR->value;
        }

        if (!self::write($target, $files)) {
            $output->writeError(sprintf('Cannot write the compiled normalizers to "%s".', $target));

            return ExitCode::CONFIG->value;
        }

        $output->writeLine(sprintf('Compiled %d DTO normalizer(s) to "%s".', count($classes), $target));

        return ExitCode::SUCCESS->value;
    }

    /**
     * The `#[Dto]` classes declared under `$directory`, sorted by name.
     *
     * @return list<class-string>
     */
    private function dtoClasses(string $directory): array
    {
        $classes = [];
        $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(
            $directory,
            FilesystemIterator::SKIP_DOTS,
        ));
        foreach ($files as $file) {
            if (!$file instanceof SplFileInfo || $file->getExtension() !== 'php') {
                continue;
            }

            $class = $this->parser->className($file->getPathname());
            if (!class_exists($class) || new ReflectionClass($class)->getAttributes(Dto::class) === []) {
                continue;
            }

            $classes[] = $class;
        }

        sort($classes);

        return $classes;
    }

    /**
     * Writes each file atomically (a temporary file renamed over it), then
     * removes the generated files no DTO needs any more.
     *
     * @param array<string, string> $files File name => PHP source.
     */
    private static function write(string $directory, array $files): bool
    {
        if (file_exists($directory) && !is_dir($directory)) {
            return false;
        }

        if (!is_dir($directory) && !mkdir($directory, 0o775, true) && !is_dir($directory)) {
            return false;
        }

        foreach ($files as $name => $source) {
            $path = $directory . '/' . $name;
            $temporary = sprintf('%s.%d.%d.tmp', $path, (int) getmypid(), hrtime(true));
            if (file_put_contents($temporary, $source) === false || !rename($temporary, $path)) {
                return false;
            }
        }

        $existing = glob($directory . '/*.php');
        foreach ($existing === false ? [] : $existing as $path) {
            if (array_key_exists(basename($path), $files)) {
                continue;
            }

            $contents = file_get_contents($path);
            if ($contents !== false && str_contains($contents, self::GENERATED_MARKER)) {
                unlink($path);
            }
        }

        return true;
    }
}
