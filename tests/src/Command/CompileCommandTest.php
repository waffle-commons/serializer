<?php

declare(strict_types=1);

namespace WaffleTests\Commons\Serializer\Command;

use PHPUnit\Framework\Attributes\CoversClass;
use Waffle\Commons\Contracts\Console\CommandInterface;
use Waffle\Commons\Contracts\Console\Enum\ExitCode;
use Waffle\Commons\Serializer\Command\CompileCommand;
use WaffleTests\Commons\Serializer\AbstractTestCase as TestCase;
use WaffleTests\Commons\Serializer\Fixture\Double\ArrayInput;
use WaffleTests\Commons\Serializer\Fixture\Double\BufferedOutput;

use function array_map;
use function basename;
use function file_get_contents;
use function file_put_contents;
use function glob;
use function is_dir;
use function is_file;
use function mkdir;
use function rmdir;
use function scandir;
use function sort;
use function unlink;

#[CoversClass(CompileCommand::class)]
final class CompileCommandTest extends TestCase
{
    private const string WORK_DIRECTORY = __DIR__ . '/../../../var/test-output';

    private const string CLASH_SOURCE = __DIR__ . '/../Fixture/Clash';

    #[\Override]
    protected function tearDown(): void
    {
        self::remove(self::WORK_DIRECTORY);
        parent::tearDown();
    }

    public function testIsAConsoleCommandNamedSerializerCompile(): void
    {
        $command = new CompileCommand();

        static::assertInstanceOf(CommandInterface::class, $command);
        static::assertSame('serializer:compile', $command->getName());
        static::assertSame(
            'Compiles the normalizer of every #[Dto] class for the WAFFLE_AOT=1 fast path.',
            $command->getDescription(),
        );
        static::assertSame(
            'serializer:compile [--source=<dir>] [--output=<dir>] [--namespace=<namespace>]',
            $command->getSynopsis(),
        );
        static::assertStringContainsString('--source=<dir>', $command->getHelp());
    }

    public function testCompilesEveryDtoUnderTheSourceDirectory(): void
    {
        $target = self::WORK_DIRECTORY . '/compiled';
        $output = new BufferedOutput();

        $code = new CompileCommand()->execute(new ArrayInput([
            'source' => self::CLASH_SOURCE,
            'output' => $target,
            'namespace' => 'App\\Generated',
        ]), $output);

        static::assertSame(ExitCode::SUCCESS->value, $code);
        static::assertSame(
            [
                'CompiledNormalizers.php',
                'WaffleTestsCommonsSerializerFixtureClashABC2Normalizer.php',
                'WaffleTestsCommonsSerializerFixtureClashABCNormalizer.php',
            ],
            self::files($target),
        );
        static::assertStringContainsString(
            'namespace App\\Generated;',
            (string) file_get_contents($target . '/CompiledNormalizers.php'),
        );
        static::assertSame('Compiled 2 DTO normalizer(s) to "' . $target . '".' . "\n", $output->out);
    }

    public function testRemovesTheGeneratedFilesNoDtoNeedsAndKeepsTheRest(): void
    {
        $target = self::WORK_DIRECTORY . '/compiled';
        mkdir($target, 0o775, true);
        file_put_contents(
            $target . '/OldNormalizer.php',
            "<?php\n// Generated by waffle-commons/serializer: do not edit, rebuild.\n",
        );
        file_put_contents($target . '/Keep.php', "<?php\n// Written by hand.\n");

        $code = new CompileCommand()->execute(new ArrayInput([
            'source' => self::CLASH_SOURCE,
            'output' => $target,
        ]), new BufferedOutput());

        static::assertSame(ExitCode::SUCCESS->value, $code);
        static::assertFalse(is_file($target . '/OldNormalizer.php'));
        static::assertTrue(is_file($target . '/Keep.php'));
    }

    public function testRefusesASourceDirectoryThatDoesNotExist(): void
    {
        $output = new BufferedOutput();

        $code = new CompileCommand()->execute(new ArrayInput(['source' => self::WORK_DIRECTORY . '/nowhere']), $output);

        static::assertSame(ExitCode::NO_INPUT->value, $code);
        static::assertSame(
            'The source directory "' . self::WORK_DIRECTORY . '/nowhere" does not exist.' . "\n",
            $output->err,
        );
    }

    public function testReportsADtoTheSerializerCannotRepresent(): void
    {
        $output = new BufferedOutput();

        $code = new CompileCommand()->execute(new ArrayInput([
            'source' => __DIR__ . '/../Fixture/Unsupported',
            'output' => self::WORK_DIRECTORY . '/compiled',
        ]), $output);

        static::assertSame(ExitCode::DATA_ERR->value, $code);
        static::assertStringStartsWith('Serializer compilation failed: ', $output->err);
    }

    public function testRefusesAnOutputThatIsAFile(): void
    {
        mkdir(self::WORK_DIRECTORY, 0o775, true);
        $file = self::WORK_DIRECTORY . '/not-a-directory';
        file_put_contents($file, '');
        $output = new BufferedOutput();

        $code = new CompileCommand()->execute(new ArrayInput([
            'source' => self::CLASH_SOURCE,
            'output' => $file,
        ]), $output);

        static::assertSame(ExitCode::CONFIG->value, $code);
        static::assertSame('Cannot write the compiled normalizers to "' . $file . '".' . "\n", $output->err);
    }

    /**
     * @return list<string>
     */
    private static function files(string $directory): array
    {
        $paths = glob($directory . '/*');
        $names = array_map(static fn(string $path): string => basename($path), $paths === false ? [] : $paths);
        sort($names);

        return $names;
    }

    private static function remove(string $path): void
    {
        if (is_file($path)) {
            unlink($path);

            return;
        }

        if (!is_dir($path)) {
            return;
        }

        $entries = scandir($path);
        foreach ($entries === false ? [] : $entries as $entry) {
            if ($entry === '.' || $entry === '..') {
                continue;
            }

            self::remove($path . '/' . $entry);
        }

        rmdir($path);
    }
}
